import WebSocket from 'ws';
import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://127.0.0.1:3000';
const data=await fetch(`${base}/cards.json`).then(r=>r.json());
assert(data.length>=20,`expected at least 20 cards, got ${data.length}`);
console.log(`✓ ${data.length} cards available`);
async function connect(params){
  const ws=new WebSocket(`${base.replace(/^http/,'ws')}/?${new URLSearchParams(params)}`);
  let latest=null,welcome=null;const waiters=[];
  ws.on('message',raw=>{const m=JSON.parse(raw);if(m.t==='welcome')welcome=m;if(m.t==='state'){latest=m.state;for(let i=waiters.length-1;i>=0;i--){if(waiters[i].test(latest)){const w=waiters.splice(i,1)[0];clearTimeout(w.timer);w.resolve(latest);}}}});
  await new Promise((resolve,reject)=>{ws.once('open',resolve);ws.once('error',reject);});
  const wait=test=>latest&&test(latest)?Promise.resolve(latest):new Promise((resolve,reject)=>{const w={test,resolve,timer:setTimeout(()=>{const i=waiters.indexOf(w);if(i>=0)waiters.splice(i,1);reject(new Error('state wait timeout'));},6000)};waiters.push(w);});
  return{ws,get latest(){return latest;},get welcome(){return welcome;},wait};
}
const deck=JSON.stringify(['squire','longbow','brute','sprinters','mystic','wisp','fireball','cannon']);
const bot=await connect({room:'TESTBOT',name:'Тестер',mode:'bot',difficulty:'easy',deck});
const botState=await bot.wait(s=>s?.phase==='playing');
assert.equal(botState.teams.length,2);assert.equal(botState.mode,'bot');
console.log('✓ бот запускает бой с выбранной сложностью');
const playerId=bot.welcome.id;
const team=botState.teams.find(t=>t.id===playerId)||botState.teams[0];
const affordable=team.hand.find(id=>data.find(c=>c.id===id).cost<=team.elixir);
assert(affordable,'starting hand should have an affordable card');
bot.ws.send(JSON.stringify({t:'play',card:affordable,lane:1,pos:.2}));
await bot.wait(s=>s?.units?.some(u=>u.team===team.id&&u.cardId===affordable));
console.log('✓ игра принимает розыгрыш карты и отражает его в состоянии');
bot.ws.close();
const host=await connect({room:'TESTDUEL',name:'Хост',mode:'friend',deck});
await host.wait(s=>s?.phase==='waiting');
const guest=await connect({room:'TESTDUEL',name:'Друг',mode:'friend',deck});
await Promise.all([host.wait(s=>s?.phase==='playing'),guest.wait(s=>s?.phase==='playing')]);
assert.equal(guest.latest.teams.length,2);
assert.equal(host.latest.teams[0].name,'Хост');
assert.equal(host.latest.teams[1].name,'Друг');
console.log('✓ два игрока подключаются в одну комнату');
host.ws.close();guest.ws.close();
console.log('Все проверки пройдены.');
